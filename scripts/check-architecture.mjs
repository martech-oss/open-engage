function createLexicalModel(sourceFile) {
  const rootScope = { bindings: new Map(), kind: "source", parent: undefined };
  const nodeScopes = new WeakMap();
  const scopesByRange = new Map();
  const declarationBindings = new WeakMap();
  const declarationBindingsByRange = new Map();
  const exportedBindings = new Set();
  const exportedDefinitions = [];
  const exportedExpressions = [];
  const exportedIdentifierNodes = [];
  const assignmentNodes = [];
  const mutationCallNodes = [];
  const classAssignments = new WeakMap();

  function nodeRangeKey(node) {
    return `${node.kind}:${node.pos}:${node.end}`;
  }

  function rememberScope(node, scope) {
    nodeScopes.set(node, scope);
    scopesByRange.set(nodeRangeKey(node), scope);
  }

  function createScope(parent, kind) {
    return { bindings: new Map(), kind, parent };
  }

  function bindIdentifier(identifier, scope, definition) {
    let binding = scope.bindings.get(identifier.text);
    if (!binding) {
      binding = { definitions: [], importSpecifiers: new Set(), name: identifier.text };
      scope.bindings.set(identifier.text, binding);
    }
    if (definition) binding.definitions.push(definition);
    declarationBindings.set(identifier, binding);
    declarationBindingsByRange.set(nodeRangeKey(identifier), binding);
    rememberScope(identifier, scope);
    return binding;
  }

  function projectedDefinition(definition, path) {
    if (!definition || path.length === 0) return definition;
    if (definition.kind === "expression") {
      return { ...definition, kind: "projection", path };
    }
    if (definition.kind === "expressions") {
      return { ...definition, kind: "projection-list", path };
    }
    return definition;
  }

  function bindName(name, scope, definition) {
    return bindingPatternLeaves(name).map(({ identifier, path }) => ({
      binding: bindIdentifier(identifier, scope, projectedDefinition(definition, path)),
      path,
    }));
  }

  function hasExportModifier(node) {
    return node.modifiers?.some((modifier) => modifier.kind === SyntaxKind.ExportKeyword) ?? false;
  }

  function visitFunction(node, outerScope) {
    let declarationBinding;
    if (isFunctionDeclaration(node) && node.name) {
      declarationBinding = bindName(node.name, outerScope, {
        kind: "function",
        node,
        ownerCallable: enclosingCallable(node),
        position: Number.NEGATIVE_INFINITY,
        write: "replace",
      })[0]?.binding;
    }
    if (isFunctionDeclaration(node) && node.parent === sourceFile && hasExportModifier(node)) {
      if (declarationBinding) exportedBindings.add(declarationBinding);
      else exportedDefinitions.push({ kind: "function", node });
    }

    const functionScope = createScope(outerScope, "function");
    if (isFunctionExpression(node) && node.name) {
      bindName(node.name, functionScope, {
        kind: "function",
        node,
        ownerCallable: node,
        position: Number.NEGATIVE_INFINITY,
        write: "replace",
      });
    }
    for (const parameter of node.parameters ?? []) {
      bindName(parameter.name, functionScope, { kind: "parameter", node: parameter });
    }
    for (const parameter of node.parameters ?? []) {
      if (parameter.initializer) visit(parameter.initializer, functionScope);
    }
    if (node.body) visit(node.body, functionScope);
  }

  function visitClass(node, outerScope) {
    let declarationBinding;
    if (isClassDeclaration(node) && node.name) {
      declarationBinding = bindName(node.name, outerScope, {
        kind: "class",
        node,
        ownerCallable: enclosingCallable(node),
        position: node.pos,
        write: "replace",
      })[0]?.binding;
    }
    if (isClassDeclaration(node) && node.parent === sourceFile && hasExportModifier(node)) {
      if (declarationBinding) exportedBindings.add(declarationBinding);
      else exportedDefinitions.push({ kind: "class", node });
    }

    const classScope = createScope(outerScope, "class");
    if (isClassExpression(node) && node.name) {
      bindName(node.name, classScope, {
        kind: "class",
        node,
        ownerCallable: enclosingCallable(node),
        position: node.pos,
        write: "replace",
      });
    }
    for (const clause of node.heritageClauses ?? []) visit(clause, classScope);
    for (const member of node.members) visit(member, classScope);
  }

  function visit(node, scope) {
    rememberScope(node, scope);

    if (isImportDeclaration(node)) {
      const specifier = staticString(node.moduleSpecifier);
      if (specifier !== undefined && node.importClause) {
        const importedNames = [];
        if (node.importClause.name) importedNames.push(node.importClause.name);
        const bindings = node.importClause.namedBindings;
        if (bindings && isNamespaceImport(bindings)) importedNames.push(bindings.name);
        else if (bindings && isNamedImports(bindings)) {
          for (const element of bindings.elements) importedNames.push(element.name);
        }
        for (const name of importedNames) {
          const binding = bindIdentifier(name, scope);
          binding.importSpecifiers.add(specifier);
        }
      }
      return;
    }
    if (isExportDeclaration(node)) {
      if (!node.moduleSpecifier && node.exportClause && isNamedExports(node.exportClause)) {
        for (const element of node.exportClause.elements) {
          const localName = element.propertyName ?? element.name;
          if (isIdentifier(localName)) exportedIdentifierNodes.push(localName);
        }
      }
      node.forEachChild((child) => visit(child, scope));
      return;
    }
    if (isExportAssignment(node)) {
      exportedExpressions.push(node.expression);
      visit(node.expression, scope);
      return;
    }
    if (isFunctionNode(node)) {
      visitFunction(node, scope);
      return;
    }
    if (isClassDeclaration(node) || isClassExpression(node)) {
      visitClass(node, scope);
      return;
    }
    if (isCatchClause(node)) {
      const catchScope = createScope(scope, "block");
      const thrownExpressions = collectThrownExpressions(node.parent?.tryBlock);
      if (node.variableDeclaration) {
        bindName(
          node.variableDeclaration.name,
          catchScope,
          thrownExpressions.length > 0
            ? {
                kind: "expressions",
                nodes: thrownExpressions,
                ownerCallable: enclosingCallable(node),
                position: node.pos,
                write: "merge",
              }
            : undefined,
        );
      }
      visit(node.block, catchScope);
      return;
    }
    if (isBlock(node)) {
      const blockScope = createScope(scope, "block");
      node.forEachChild((child) => visit(child, blockScope));
      return;
    }
    if (isVariableDeclaration(node)) {
      const definition = node.initializer
        ? {
            kind: "expression",
            node: node.initializer,
            ownerCallable: enclosingCallable(node),
            position: node.initializer.end,
            write: "replace",
          }
        : {
            kind: hasDeclareModifier(node) ? "unknown" : "undefined",
            node,
            ownerCallable: enclosingCallable(node),
            position: node.pos,
            write: "replace",
          };
      const declarationScope = isBlockScopedVariableDeclaration(node)
        ? scope
        : nearestVarScope(scope);
      const bindings = bindName(node.name, declarationScope, definition);
      const statement = node.parent?.parent;
      if (
        statement &&
        isVariableStatement(statement) &&
        statement.parent === sourceFile &&
        hasExportModifier(statement)
      ) {
        for (const { binding } of bindings) exportedBindings.add(binding);
      }
      if (node.initializer) visit(node.initializer, scope);
      return;
    }
    if (isBinaryExpression(node) && assignmentWriteKind(node.operatorToken.kind)) {
      assignmentNodes.push(node);
    }
    if (isCallExpression(node)) mutationCallNodes.push(node);
    node.forEachChild((child) => visit(child, scope));
  }

  function resolveIdentifier(identifier) {
    const declarationBinding =
      declarationBindings.get(identifier) ??
      declarationBindingsByRange.get(nodeRangeKey(identifier));
    if (declarationBinding) return declarationBinding;
    let scope =
      nodeScopes.get(identifier) ?? scopesByRange.get(nodeRangeKey(identifier)) ?? rootScope;
    while (scope) {
      const binding = scope.bindings.get(identifier.text);
      if (binding) return binding;
      scope = scope.parent;
    }
    return undefined;
  }

  visit(sourceFile, rootScope);
  for (const identifier of exportedIdentifierNodes) {
    const binding = resolveIdentifier(identifier);
    if (binding) exportedBindings.add(binding);
  }

  for (const assignment of assignmentNodes) {
    let write = assignmentWriteKind(assignment.operatorToken.kind);
    if (!write) continue;
    if (write === "replace" && mutationIsConditional(assignment)) write = "merge";
    for (const { identifier, path } of assignmentPatternLeaves(assignment.left)) {
      const binding = resolveIdentifier(identifier);
      if (!binding) continue;
      binding.definitions.push(
        projectedDefinition(
          {
            kind: "expression",
            node: assignment.right,
            ownerCallable: enclosingCallable(assignment),
            position: assignment.end,
            write,
          },
          path,
        ),
      );
    }
  }

  function classesForExpression(expression, seenBindings = new Set()) {
    const node = unwrapTransparentExpression(expression);
    if (isClassDeclaration(node) || isClassExpression(node)) return [node];
    if (isConditionalExpression(node)) {
      return [
        ...classesForExpression(node.whenTrue, seenBindings),
        ...classesForExpression(node.whenFalse, seenBindings),
      ];
    }
    if (!isIdentifier(node)) return [];
    const binding = resolveIdentifier(node);
    if (!binding || seenBindings.has(binding)) return [];
    seenBindings.add(binding);
    return binding.definitions.flatMap((definition) => {
      if (definition.kind === "class") return [definition.node];
      if (definition.kind === "expression") {
        return classesForExpression(definition.node, seenBindings);
      }
      return [];
    });
  }

  function classesForReceiver(receiver) {
    receiver = unwrapTransparentExpression(receiver);
    if (receiver.kind === SyntaxKind.ThisKeyword) {
      const owner = enclosingThisClass(receiver);
      return owner ? [owner] : [];
    }
    return classesForExpression(receiver);
  }

  function recordClassAssignment(owner, member, node, mutation, targetName, writeOverride) {
    let write = writeOverride ?? assignmentWriteKind(mutation.operatorToken?.kind) ?? "replace";
    if (write === "replace" && mutationIsConditional(mutation)) write = "merge";
    const records = classAssignments.get(owner) ?? [];
    records.push({
      member,
      node,
      ownerCallable: enclosingCallable(mutation, owner),
      position: mutation.end,
      private: targetName ? isPrivateIdentifier(targetName) : false,
      write,
    });
    classAssignments.set(owner, records);
  }

  for (const assignment of assignmentNodes) {
    const target = unwrapTransparentExpression(assignment.left);
    if (!isPropertyAccessExpression(target) && !isElementAccessExpression(target)) continue;
    const member = isPropertyAccessExpression(target)
      ? classMemberName(target.name)
      : staticString(target.argumentExpression);
    if (member === undefined) continue;
    const receiver = unwrapTransparentExpression(target.expression);
    for (const owner of classesForReceiver(receiver)) {
      recordClassAssignment(
        owner,
        member,
        assignment.right,
        assignment,
        isPropertyAccessExpression(target) ? target.name : target.argumentExpression,
      );
    }
  }

  for (const call of mutationCallNodes) {
    const callee = unwrapTransparentExpression(call.expression);
    if (
      !isPropertyAccessExpression(callee) ||
      !isIdentifier(callee.expression) ||
      callee.expression.text !== "Object" ||
      callee.name.text !== "assign" ||
      resolveIdentifier(callee.expression) ||
      call.arguments.length < 2
    ) {
      continue;
    }
    const receiver = call.arguments[0];
    for (const owner of classesForReceiver(receiver)) {
      for (const source of call.arguments.slice(1)) {
        for (const { member, node, write } of objectMutationEntries(
          source,
          call,
          resolveIdentifier,
        )) {
          recordClassAssignment(owner, member, node, call, undefined, write);
        }
      }
    }
  }

  return {
    assignmentsForClass: (node) => classAssignments.get(node) ?? [],
    bindingEntriesForName: (name) =>
      bindNameEntries(name, declarationBindings, declarationBindingsByRange),
    classForThis: enclosingThisClass,
    exportedBindings,
    exportedDefinitions,
    exportedExpressions,
    resolveIdentifier,
  };
}

function isBlockScopedVariableDeclaration(node) {
  return Boolean(node.parent?.flags & NodeFlags.BlockScoped);
}

function nearestVarScope(scope) {
  while (scope.parent && scope.kind !== "function" && scope.kind !== "source") {
    scope = scope.parent;
  }
  return scope;
}

function hasDeclareModifier(node) {
  const declarationModifiers = node.modifiers ?? [];
  const statementModifiers = isVariableStatement(node.parent?.parent)
    ? (node.parent.parent.modifiers ?? [])
    : [];
  return [...declarationModifiers, ...statementModifiers].some(
    (modifier) => modifier.kind === SyntaxKind.DeclareKeyword,
  );
}

function assignmentWriteKind(kind) {
  if (kind === SyntaxKind.EqualsToken) return "replace";
  if (
    kind === SyntaxKind.QuestionQuestionEqualsToken ||
    kind === SyntaxKind.BarBarEqualsToken ||
    kind === SyntaxKind.AmpersandAmpersandEqualsToken
  ) {
    return "merge";
  }
  return undefined;
}

function mutationIsConditional(node) {
  let current = node.parent;
  while (current) {
    if (isFunctionNode(current)) return false;
    if (
      [
        SyntaxKind.IfStatement,
        SyntaxKind.ConditionalExpression,
        SyntaxKind.SwitchStatement,
        SyntaxKind.CaseBlock,
        SyntaxKind.ForStatement,
        SyntaxKind.ForInStatement,
        SyntaxKind.ForOfStatement,
        SyntaxKind.WhileStatement,
        SyntaxKind.DoStatement,
        SyntaxKind.TryStatement,
        SyntaxKind.CatchClause,
      ].includes(current.kind)
    ) {
      return true;
    }
    if (
      isBinaryExpression(current) &&
      [
        SyntaxKind.AmpersandAmpersandToken,
        SyntaxKind.BarBarToken,
        SyntaxKind.QuestionQuestionToken,
      ].includes(current.operatorToken.kind)
    ) {
      return true;
    }
    current = current.parent;
  }
  return false;
}

function assignmentPatternLeaves(name) {
  const leaves = [];
  const pending = [{ name: unwrapTransparentExpression(name), path: [] }];
  while (pending.length > 0) {
    const current = pending.pop();
    const target = unwrapTransparentExpression(current.name);
    if (isIdentifier(target)) {
      leaves.push({ identifier: target, path: current.path });
      continue;
    }
    if (isArrayLiteralExpression(target)) {
      for (let index = target.elements.length - 1; index >= 0; index -= 1) {
        let element = target.elements[index];
        if (!element || element.kind === SyntaxKind.OmittedExpression) continue;
        let defaultNode;
        let rest = false;
        if (isSpreadElement(element)) {
          rest = true;
          element = element.expression;
        }
        element = unwrapTransparentExpression(element);
        if (isBinaryExpression(element) && element.operatorToken.kind === SyntaxKind.EqualsToken) {
          defaultNode = element.right;
          element = element.left;
        }
        pending.push({
          name: element,
          path: [...current.path, { defaultNode, index, kind: "array", rest }],
        });
      }
      continue;
    }
    if (!isObjectLiteralExpression(target)) continue;
    const excludedKeys = target.properties
      .filter((property) => !isSpreadAssignment(property))
      .map((property) => classMemberName(property.name))
      .filter((key) => key !== undefined);
    for (let index = target.properties.length - 1; index >= 0; index -= 1) {
      const property = target.properties[index];
      if (isSpreadAssignment(property)) {
        pending.push({
          name: property.expression,
          path: [
            ...current.path,
            {
              excludedKeys,
              key: undefined,
              kind: "object",
              rest: true,
            },
          ],
        });
        continue;
      }
      if (isShorthandPropertyAssignment(property)) {
        pending.push({
          name: property.name,
          path: [
            ...current.path,
            {
              defaultNode: property.objectAssignmentInitializer,
              excludedKeys,
              key: property.name.text,
              kind: "object",
              rest: false,
            },
          ],
        });
        continue;
      }
      if (!isPropertyAssignment(property)) continue;
      let propertyTarget = unwrapTransparentExpression(property.initializer);
      let defaultNode;
      if (
        isBinaryExpression(propertyTarget) &&
        propertyTarget.operatorToken.kind === SyntaxKind.EqualsToken
      ) {
        defaultNode = propertyTarget.right;
        propertyTarget = propertyTarget.left;
      }
      pending.push({
        name: propertyTarget,
        path: [
          ...current.path,
          {
            defaultNode,
            excludedKeys,
            key: classMemberName(property.name),
            kind: "object",
            rest: false,
          },
        ],
      });
    }
  }
  return leaves;
}

function objectMutationEntries(expression, reference, resolveIdentifier, seenBindings = new Set()) {
  const node = unwrapTransparentExpression(expression);
  if (isIdentifier(node)) {
    const binding = resolveIdentifier(node);
    if (!binding || seenBindings.has(binding)) return [];
    const nestedSeen = new Set(seenBindings);
    nestedSeen.add(binding);
    return effectiveLocalObjectDefinitions(binding, reference).flatMap((definition) =>
      objectMutationEntries(definition.node, reference, resolveIdentifier, nestedSeen).map(
        (entry) => ({
          ...entry,
          write: definition.write === "merge" ? "merge" : entry.write,
        }),
      ),
    );
  }
  if (!isObjectLiteralExpression(node)) return [];
  const entries = [];
  for (const property of node.properties) {
    if (isPropertyAssignment(property)) {
      const member = classMemberName(property.name);
      if (member !== undefined) entries.push({ member, node: property.initializer });
    } else if (isShorthandPropertyAssignment(property)) {
      entries.push({ member: property.name.text, node: property.name });
    } else if (isSpreadAssignment(property)) {
      entries.push(
        ...objectMutationEntries(property.expression, reference, resolveIdentifier, seenBindings),
      );
    }
  }
  return entries;
}

// Deliberate boundary: Object.assign analysis expands only local bindings that resolve to
// object literals. Custom helpers, computed sources, and arbitrary receivers stay outside this
// rule. Mutating a source object's field after its literal initialization is also not modeled,
// so a later safe field overwrite can remain conservatively tainted.
function effectiveLocalObjectDefinitions(binding, reference) {
  const referenceCallable = enclosingCallable(reference);
  const referencePosition = reference.pos;
  const moduleDefinitions = [];
  const callableDefinitions = [];
  for (const definition of binding.definitions) {
    if (definition.kind !== "expression") continue;
    const definitionPosition = definition.position ?? Number.NEGATIVE_INFINITY;
    if (definition.ownerCallable === undefined) {
      if (referenceCallable || definitionPosition <= referencePosition) {
        moduleDefinitions.push(definition);
      }
    } else if (
      definition.ownerCallable === referenceCallable &&
      definitionPosition <= referencePosition
    ) {
      callableDefinitions.push(definition);
    }
  }
  let effective = [];
  const byPosition = (left, right) =>
    (left.position ?? Number.NEGATIVE_INFINITY) - (right.position ?? Number.NEGATIVE_INFINITY);
  for (const definition of [
    ...moduleDefinitions.sort(byPosition),
    ...callableDefinitions.sort(byPosition),
  ]) {
    if (definition.write === "replace") effective = [definition];
    else effective.push(definition);
  }
  return effective;
}

function collectThrownExpressions(node) {
  if (!node) return [];
  const expressions = [];
  const pending = [node];
  while (pending.length > 0) {
    const current = pending.pop();
    if (isThrowStatement(current)) {
      if (current.expression) expressions.push(current.expression);
      continue;
    }
    if (
      current !== node &&
      (isFunctionNode(current) || isClassDeclaration(current) || isClassExpression(current))
    ) {
      continue;
    }
    current.forEachChild((child) => {
      pending.push(child);
    });
  }
  return expressions;
}

function bindNameEntries(name, declarationBindings, declarationBindingsByRange) {
  return bindingPatternLeaves(name).flatMap(({ identifier, path }) => {
    const binding =
      declarationBindings.get(identifier) ??
      declarationBindingsByRange.get(`${identifier.kind}:${identifier.pos}:${identifier.end}`);
    return binding ? [{ binding, path }] : [];
  });
}

function bindingPatternLeaves(name) {
  if (!name) return [];
  const leaves = [];
  const pending = [{ name, path: [] }];
  while (pending.length > 0) {
    const current = pending.pop();
    if (!current.name) continue;
    if (isIdentifier(current.name)) {
      leaves.push({ identifier: current.name, path: current.path });
      continue;
    }
    if (isArrayBindingPattern(current.name)) {
      for (let index = current.name.elements.length - 1; index >= 0; index -= 1) {
        const element = current.name.elements[index];
        if (!element || !isBindingElement(element) || !element.name) continue;
        pending.push({
          name: element.name,
          path: [
            ...current.path,
            {
              defaultNode: element.initializer,
              index,
              kind: "array",
              rest: Boolean(element.dotDotDotToken),
            },
          ],
        });
      }
      continue;
    }
    if (!isObjectBindingPattern(current.name)) continue;
    const excludedKeys = current.name.elements
      .filter((element) => element && isBindingElement(element) && !element.dotDotDotToken)
      .map((element) => staticPropertyName(element.propertyName ?? element.name))
      .filter((key) => key !== undefined);
    for (let index = current.name.elements.length - 1; index >= 0; index -= 1) {
      const element = current.name.elements[index];
      if (!element || !isBindingElement(element) || !element.name) continue;
      pending.push({
        name: element.name,
        path: [
          ...current.path,
          {
            defaultNode: element.initializer,
            excludedKeys,
            key: element.dotDotDotToken
              ? undefined
              : staticPropertyName(element.propertyName ?? element.name),
            kind: "object",
            rest: Boolean(element.dotDotDotToken),
          },
        ],
      });
    }
  }
  return leaves;
}

function classMemberName(name) {
  if (!name) return undefined;
  if (isPrivateIdentifier(name)) return name.text;
  return staticPropertyName(name);
}

function enclosingThisClass(node) {
  let current = node.parent;
  while (current) {
    if (isClassDeclaration(current) || isClassExpression(current)) return current;
    if (isFunctionDeclaration(current) || isFunctionExpression(current)) {
      return undefined;
    }
    current = current.parent;
  }
  return undefined;
}

function enclosingCallable(node, boundary) {
  let current = node.parent;
  while (current && current !== boundary) {
    if (isFunctionNode(current)) return current;
    current = current.parent;
  }
  return undefined;
}

function isFunctionNode(node) {
  return (
    isFunctionDeclaration(node) ||
    isFunctionExpression(node) ||
    isArrowFunction(node) ||
    isMethodDeclaration(node) ||
    isGetAccessorDeclaration(node) ||
    isSetAccessorDeclaration(node) ||
    isConstructorDeclaration(node)
  );
}

function bindingIsCallableSurface(binding) {
  return binding.definitions.some(definitionIsCallableSurface);
}

function definitionIsCallableSurface(definition) {
  if (definition.kind === "function" || definition.kind === "class") return true;
  return definition.kind === "expression" && expressionIsCallableSurface(definition.node);
}

function expressionIsCallableSurface(expression) {
  const node = unwrapTransparentExpression(expression);
  return isFunctionNode(node) || isClassDeclaration(node) || isClassExpression(node);
}

function createProvenanceAnalyzer(model) {
  function createContext(parent) {
    return {
      activeCallables: parent?.activeCallables ?? new Set(),
      activeClasses: parent?.activeClasses ?? new Set(),
      activeMemberClasses: parent?.activeMemberClasses ?? new Map(),
      cache: new Map(),
      classInstanceContexts: parent?.classInstanceContexts ?? new Map(),
      overrides: new Map(parent?.overrides ?? []),
      sourceOverrides: new Map(parent?.sourceOverrides ?? []),
      resolving: new Map(),
      resolvingDefinedness: new Map(),
    };
  }

  function referencePosition(reference) {
    return reference?.pos ?? Number.POSITIVE_INFINITY;
  }

  function effectiveDefinitions(binding, reference) {
    const position = referencePosition(reference);
    const referenceCallable = reference ? enclosingCallable(reference) : undefined;
    const groups = new Map();
    for (const definition of binding.definitions) {
      const definitionPosition = definition.position ?? Number.NEGATIVE_INFINITY;
      const sameExecution = definition.ownerCallable === referenceCallable;
      if (reference && sameExecution && definitionPosition > position) continue;
      const definitions = groups.get(definition.ownerCallable) ?? [];
      definitions.push(definition);
      groups.set(definition.ownerCallable, definitions);
    }
    const effective = [];
    for (const definitions of groups.values()) {
      let groupValues = [];
      for (const definition of definitions.sort(
        (left, right) =>
          (left.position ?? Number.NEGATIVE_INFINITY) -
          (right.position ?? Number.NEGATIVE_INFINITY),
      )) {
        if (definition.write === "replace") groupValues = [definition];
        else groupValues.push(definition);
      }
      effective.push(...groupValues);
    }
    return effective;
  }

  function bindingProvenance(binding, context, reference) {
    if (context.overrides.has(binding)) return context.overrides.get(binding).provenance;
    const position = referencePosition(reference);
    let bindingCache = context.cache.get(binding);
    if (!bindingCache) {
      bindingCache = new Map();
      context.cache.set(binding, bindingCache);
    }
    if (bindingCache.has(position)) return bindingCache.get(position);
    const resolvingPositions = context.resolving.get(binding) ?? new Set();
    if (resolvingPositions.has(position)) return new Set();

    resolvingPositions.add(position);
    context.resolving.set(binding, resolvingPositions);
    const provenance = new Set(binding.importSpecifiers);
    for (const definition of effectiveDefinitions(binding, reference)) {
      addProvenance(provenance, definitionProvenance(definition, context));
    }
    resolvingPositions.delete(position);
    if (resolvingPositions.size === 0) context.resolving.delete(binding);
    bindingCache.set(position, provenance);
    return provenance;
  }

  function bindingDefinedness(binding, context, reference) {
    if (context.overrides.has(binding)) return context.overrides.get(binding).definedness;
    const position = referencePosition(reference);
    const resolvingPositions = context.resolvingDefinedness.get(binding) ?? new Set();
    if (resolvingPositions.has(position)) return "unknown";
    resolvingPositions.add(position);
    context.resolvingDefinedness.set(binding, resolvingPositions);
    try {
      const definitions = effectiveDefinitions(binding, reference);
      if (definitions.length === 0) return "unknown";
      return joinDefinedness(
        definitions.map((definition) => definitionDefinedness(definition, context)),
      );
    } finally {
      resolvingPositions.delete(position);
      if (resolvingPositions.size === 0) context.resolvingDefinedness.delete(binding);
    }
  }

  function definitionProvenance(definition, context) {
    if (definition.kind === "expression") return expressionProvenance(definition.node, context);
    if (definition.kind === "expressions") {
      const provenance = new Set();
      for (const node of definition.nodes) {
        addProvenance(provenance, expressionProvenance(node, context));
      }
      return provenance;
    }
    if (definition.kind === "projection") {
      return projectedExpressionProvenance(definition.node, definition.path, context);
    }
    if (definition.kind === "projection-list") {
      const provenance = new Set();
      for (const node of definition.nodes) {
        addProvenance(provenance, projectedExpressionProvenance(node, definition.path, context));
      }
      return provenance;
    }
    if (definition.kind === "function") return callableOutputProvenance(definition.node, context);
    if (definition.kind === "class") return classOutputProvenance(definition.node, context);
    return new Set();
  }

  function definitionDefinedness(definition, context) {
    if (definition.kind === "undefined") return "undefined";
    if (definition.kind === "unknown" || definition.kind === "parameter") return "unknown";
    if (definition.kind === "expression") return expressionDefinedness(definition.node, context);
    if (definition.kind === "expressions") {
      return joinDefinedness(definition.nodes.map((node) => expressionDefinedness(node, context)));
    }
    if (definition.kind === "projection") {
      return projectedExpressionFact(definition.node, definition.path, context).definedness;
    }
    if (definition.kind === "projection-list") {
      return joinDefinedness(
        definition.nodes.map(
          (node) => projectedExpressionFact(node, definition.path, context).definedness,
        ),
      );
    }
    if (definition.kind === "function" || definition.kind === "class") return "nonundefined";
    return "unknown";
  }

  function valueFact(provenance = new Set(), definedness = "unknown") {
    return { definedness, provenance };
  }

  function joinDefinedness(values) {
    const known = new Set(values);
    if (known.size === 1) return values[0];
    return "unknown";
  }

  function mergeFacts(facts, definedness) {
    const provenance = new Set();
    for (const fact of facts) addProvenance(provenance, fact.provenance);
    return valueFact(
      provenance,
      definedness ??
        (facts.length > 0 ? joinDefinedness(facts.map((fact) => fact.definedness)) : "unknown"),
    );
  }

  function expressionFact(expression, context) {
    if (!expression) return valueFact(new Set(), "undefined");
    return valueFact(
      expressionProvenance(expression, context),
      expressionDefinedness(expression, context),
    );
  }

  function projectedExpressionProvenance(expression, path, context, pathIndex = 0) {
    return projectedExpressionFact(expression, path, context, pathIndex).provenance;
  }

  function projectedExpressionFact(
    expression,
    path,
    context,
    pathIndex = 0,
    seenBindings = new Set(),
  ) {
    if (pathIndex >= path.length) return expressionFact(expression, context);
    const step = path[pathIndex];
    if (!expression) {
      return applyProjectionDefault(
        valueFact(new Set(), "undefined"),
        step.defaultNode,
        path,
        context,
        pathIndex + 1,
      );
    }

    const node = unwrapTransparentExpression(expression);
    if (isIdentifier(node)) {
      const binding = model.resolveIdentifier(node);
      if (binding && !seenBindings.has(binding)) {
        const nestedSeen = new Set(seenBindings);
        nestedSeen.add(binding);
        const sourceOverride = context.sourceOverrides.get(binding);
        if (sourceOverride) {
          return mergeFacts(
            sourceOverride.expressions.map((source) =>
              projectedExpressionFact(source, path, sourceOverride.context, pathIndex, nestedSeen),
            ),
          );
        }
        const facts = effectiveDefinitions(binding, node).map((definition) => {
          if (definition.kind === "expression") {
            return projectedExpressionFact(definition.node, path, context, pathIndex, nestedSeen);
          }
          if (definition.kind === "expressions") {
            return mergeFacts(
              definition.nodes.map((source) =>
                projectedExpressionFact(source, path, context, pathIndex, nestedSeen),
              ),
            );
          }
          const fact = valueFact(
            definitionProvenance(definition, context),
            definitionDefinedness(definition, context),
          );
          return applyProjectionDefault(fact, step.defaultNode, path, context, pathIndex + 1);
        });
        if (facts.length > 0) return mergeFacts(facts);
      }
    }

    if (step.kind === "array" && isArrayLiteralExpression(node)) {
      if (step.rest) {
        const facts = [];
        for (const element of node.elements.slice(step.index)) {
          if (!element || element.kind === SyntaxKind.OmittedExpression) continue;
          facts.push(
            projectedExpressionFact(
              isSpreadElement(element) ? element.expression : element,
              path,
              context,
              pathIndex + 1,
              seenBindings,
            ),
          );
        }
        return mergeFacts(facts, "nonundefined");
      }
      const element = node.elements[step.index];
      if (!element || element.kind === SyntaxKind.OmittedExpression) {
        return applyProjectionDefault(
          valueFact(new Set(), "undefined"),
          step.defaultNode,
          path,
          context,
          pathIndex + 1,
        );
      }
      if (isSpreadElement(element)) {
        return applyProjectionDefault(
          valueFact(expressionProvenance(element.expression, context), "unknown"),
          step.defaultNode,
          path,
          context,
          pathIndex + 1,
        );
      }
      return applyProjectionDefault(
        projectedExpressionFact(element, path, context, pathIndex + 1, seenBindings),
        step.defaultNode,
        path,
        context,
        pathIndex + 1,
        expressionDefinedness(element, context),
      );
    }

    if (step.kind === "object") {
      if (step.rest) {
        return objectRestFact(node, step.excludedKeys, context, seenBindings);
      }
      if (step.key !== undefined) {
        const selection = objectPropertySelection(
          node,
          step.key,
          path,
          context,
          pathIndex + 1,
          seenBindings,
        );
        const selected =
          selection.presence === "absent"
            ? valueFact(new Set(), "undefined")
            : valueFact(selection.provenance, selection.definedness);
        return applyProjectionDefault(selected, step.defaultNode, path, context, pathIndex + 1);
      }
    }

    return applyProjectionDefault(
      expressionFact(node, context),
      step.defaultNode,
      path,
      context,
      pathIndex + 1,
    );
  }

  function applyProjectionDefault(
    selected,
    defaultNode,
    path,
    context,
    nextPathIndex,
    selectedDefinedness = selected.definedness,
  ) {
    if (!defaultNode || selectedDefinedness === "nonundefined") return selected;
    const fallback = projectedExpressionFact(defaultNode, path, context, nextPathIndex);
    if (selectedDefinedness === "undefined") return fallback;
    const definedness = fallback.definedness === "nonundefined" ? "nonundefined" : "unknown";
    return mergeFacts([selected, fallback], definedness);
  }

  function emptyObjectSelection() {
    return { definedness: "undefined", presence: "absent", provenance: new Set() };
  }

  function selectionForProperty(property, path, context, nextPathIndex, seenBindings) {
    let expression;
    if (isPropertyAssignment(property)) expression = property.initializer;
    else if (isShorthandPropertyAssignment(property)) expression = property.name;
    else if (isMethodDeclaration(property) || isGetAccessorDeclaration(property)) {
      return {
        definedness: "nonundefined",
        presence: "present",
        provenance: callableOutputProvenance(property, context),
      };
    } else {
      return { definedness: "unknown", presence: "unknown", provenance: new Set() };
    }
    const fact = projectedExpressionFact(expression, path, context, nextPathIndex, seenBindings);
    return {
      definedness: expressionDefinedness(expression, context),
      presence: "present",
      provenance: fact.provenance,
    };
  }

  function mergeAlternativeSelections(selections) {
    if (selections.length === 0) return emptyObjectSelection();
    const provenance = new Set();
    for (const selection of selections) addProvenance(provenance, selection.provenance);
    const presences = new Set(selections.map((selection) => selection.presence));
    return {
      definedness: joinDefinedness(selections.map((selection) => selection.definedness)),
      presence: presences.size === 1 ? selections[0].presence : "unknown",
      provenance,
    };
  }

  function overlayObjectSelection(previous, incoming) {
    if (incoming.presence === "absent") return previous;
    if (incoming.presence === "present") return incoming;
    const provenance = new Set(previous.provenance);
    addProvenance(provenance, incoming.provenance);
    return {
      definedness: joinDefinedness([previous.definedness, incoming.definedness]),
      presence: previous.presence === "present" ? "present" : "unknown",
      provenance,
    };
  }

  function objectPropertySelection(expression, key, path, context, nextPathIndex, seenBindings) {
    const node = unwrapTransparentExpression(expression);
    if (isObjectLiteralExpression(node)) {
      let selection = emptyObjectSelection();
      for (const property of node.properties) {
        if (isSpreadAssignment(property)) {
          selection = overlayObjectSelection(
            selection,
            objectPropertySelection(
              property.expression,
              key,
              path,
              context,
              nextPathIndex,
              seenBindings,
            ),
          );
          continue;
        }
        const propertyKey = classMemberName(property.name);
        if (propertyKey === key) {
          selection = selectionForProperty(property, path, context, nextPathIndex, seenBindings);
        } else if (propertyKey === undefined) {
          selection = overlayObjectSelection(selection, {
            definedness: "unknown",
            presence: "unknown",
            provenance: objectPropertyValueProvenance(property, context),
          });
        }
      }
      return selection;
    }
    if (isConditionalExpression(node)) {
      return mergeAlternativeSelections([
        objectPropertySelection(node.whenTrue, key, path, context, nextPathIndex, seenBindings),
        objectPropertySelection(node.whenFalse, key, path, context, nextPathIndex, seenBindings),
      ]);
    }
    if (isIdentifier(node)) {
      const binding = model.resolveIdentifier(node);
      if (binding && !seenBindings.has(binding)) {
        const nestedSeen = new Set(seenBindings);
        nestedSeen.add(binding);
        const sourceOverride = context.sourceOverrides.get(binding);
        if (sourceOverride) {
          return mergeAlternativeSelections(
            sourceOverride.expressions.map((source) =>
              objectPropertySelection(
                source,
                key,
                path,
                sourceOverride.context,
                nextPathIndex,
                nestedSeen,
              ),
            ),
          );
        }
        const selections = effectiveDefinitions(binding, node).flatMap((definition) => {
          if (definition.kind === "expression") {
            return [
              objectPropertySelection(
                definition.node,
                key,
                path,
                context,
                nextPathIndex,
                nestedSeen,
              ),
            ];
          }
          if (definition.kind === "expressions") {
            return definition.nodes.map((source) =>
              objectPropertySelection(source, key, path, context, nextPathIndex, nestedSeen),
            );
          }
          return [];
        });
        if (selections.length > 0) return mergeAlternativeSelections(selections);
      }
    }
    return {
      definedness: "unknown",
      presence: "unknown",
      provenance: expressionProvenance(node, context),
    };
  }

  function objectPropertyValueProvenance(property, context) {
    if (isPropertyAssignment(property)) return expressionProvenance(property.initializer, context);
    if (isShorthandPropertyAssignment(property)) {
      return expressionProvenance(property.name, context);
    }
    if (isMethodDeclaration(property) || isGetAccessorDeclaration(property)) {
      return callableOutputProvenance(property, context);
    }
    return new Set();
  }

  function objectRestFact(expression, excludedKeys, context, seenBindings) {
    const shape = objectShape(expression, context, seenBindings);
    const provenance = new Set(shape.unknownProvenance);
    for (const [key, fact] of shape.properties) {
      if (!excludedKeys.includes(key)) addProvenance(provenance, fact.provenance);
    }
    return valueFact(provenance, "nonundefined");
  }

  function objectShape(expression, context, seenBindings = new Set()) {
    const node = unwrapTransparentExpression(expression);
    if (isObjectLiteralExpression(node)) {
      const shape = { properties: new Map(), unknownProvenance: new Set() };
      for (const property of node.properties) {
        if (isSpreadAssignment(property)) {
          const spreadShape = objectShape(property.expression, context, seenBindings);
          for (const [key, fact] of spreadShape.properties) shape.properties.set(key, fact);
          addProvenance(shape.unknownProvenance, spreadShape.unknownProvenance);
          continue;
        }
        const key = classMemberName(property.name);
        if (key === undefined) {
          addProvenance(shape.unknownProvenance, objectPropertyValueProvenance(property, context));
          continue;
        }
        shape.properties.set(
          key,
          valueFact(objectPropertyValueProvenance(property, context), "unknown"),
        );
      }
      return shape;
    }
    if (isIdentifier(node)) {
      const binding = model.resolveIdentifier(node);
      if (binding && !seenBindings.has(binding)) {
        const nestedSeen = new Set(seenBindings);
        nestedSeen.add(binding);
        const sourceOverride = context.sourceOverrides.get(binding);
        if (sourceOverride) {
          return mergeObjectShapes(
            sourceOverride.expressions.map((source) =>
              objectShape(source, sourceOverride.context, nestedSeen),
            ),
          );
        }
        const shapes = effectiveDefinitions(binding, node).flatMap((definition) => {
          if (definition.kind === "expression") {
            return [objectShape(definition.node, context, nestedSeen)];
          }
          if (definition.kind === "expressions") {
            return definition.nodes.map((source) => objectShape(source, context, nestedSeen));
          }
          return [];
        });
        if (shapes.length > 0) return mergeObjectShapes(shapes);
      }
    }
    return { properties: new Map(), unknownProvenance: expressionProvenance(node, context) };
  }

  function mergeObjectShapes(shapes) {
    const merged = { properties: new Map(), unknownProvenance: new Set() };
    for (const shape of shapes) {
      addProvenance(merged.unknownProvenance, shape.unknownProvenance);
      for (const [key, fact] of shape.properties) {
        const previous = merged.properties.get(key);
        merged.properties.set(key, previous ? mergeFacts([previous, fact]) : fact);
      }
    }
    return merged;
  }

  function expressionDefinedness(expression, context) {
    if (!expression) return "undefined";
    const node = unwrapTransparentExpression(expression);
    if (isIdentifier(node)) {
      if (node.text === "undefined" && !model.resolveIdentifier(node)) return "undefined";
      const binding = model.resolveIdentifier(node);
      return binding ? bindingDefinedness(binding, context, node) : "unknown";
    }
    if (
      isObjectLiteralExpression(node) ||
      isArrayLiteralExpression(node) ||
      isFunctionNode(node) ||
      isClassDeclaration(node) ||
      isClassExpression(node) ||
      isNewExpression(node)
    ) {
      return "nonundefined";
    }
    if (
      [
        SyntaxKind.StringLiteral,
        SyntaxKind.NoSubstitutionTemplateLiteral,
        SyntaxKind.NumericLiteral,
        SyntaxKind.BigIntLiteral,
        SyntaxKind.RegularExpressionLiteral,
        SyntaxKind.TrueKeyword,
        SyntaxKind.FalseKeyword,
        SyntaxKind.NullKeyword,
      ].includes(node.kind)
    ) {
      return "nonundefined";
    }
    if (node.kind === SyntaxKind.VoidExpression) return "undefined";
    if (isConditionalExpression(node)) {
      return joinDefinedness([
        expressionDefinedness(node.whenTrue, context),
        expressionDefinedness(node.whenFalse, context),
      ]);
    }
    if (isAwaitExpression(node)) return expressionDefinedness(node.expression, context);
    if (isBinaryExpression(node)) {
      if (
        node.operatorToken.kind === SyntaxKind.EqualsToken ||
        node.operatorToken.kind === SyntaxKind.CommaToken
      ) {
        return expressionDefinedness(node.right, context);
      }
      if (
        node.operatorToken.kind === SyntaxKind.AmpersandAmpersandToken ||
        node.operatorToken.kind === SyntaxKind.BarBarToken ||
        node.operatorToken.kind === SyntaxKind.QuestionQuestionToken
      ) {
        return joinDefinedness([
          expressionDefinedness(node.left, context),
          expressionDefinedness(node.right, context),
        ]);
      }
    }
    if (
      isCallExpression(node) &&
      isKnownPrimitiveSanitizer(node.expression) &&
      !model.resolveIdentifier(unwrapTransparentExpression(node.expression))
    ) {
      return "nonundefined";
    }
    return "unknown";
  }

  function expressionProvenance(expression, context) {
    const provenance = new Set();
    const pending = [expression];
    while (pending.length > 0) {
      const node = unwrapTransparentExpression(pending.pop());
      if (isIdentifier(node)) {
        const binding = model.resolveIdentifier(node);
        if (binding) addProvenance(provenance, bindingProvenance(binding, context, node));
      } else if (isFunctionNode(node)) {
        addProvenance(provenance, callableOutputProvenance(node, context));
      } else if (isClassDeclaration(node) || isClassExpression(node)) {
        addProvenance(provenance, classOutputProvenance(node, context));
      } else if (isPropertyAccessExpression(node)) {
        const owner =
          unwrapTransparentExpression(node.expression).kind === SyntaxKind.ThisKeyword
            ? model.classForThis(node)
            : undefined;
        const member = classMemberName(node.name);
        if (owner && member !== undefined) {
          addProvenance(provenance, classMemberValueProvenance(owner, member, context));
        } else {
          pending.push(node.expression);
        }
      } else if (isElementAccessExpression(node)) {
        const owner =
          unwrapTransparentExpression(node.expression).kind === SyntaxKind.ThisKeyword
            ? model.classForThis(node)
            : undefined;
        const member = staticString(node.argumentExpression);
        if (owner && member !== undefined) {
          addProvenance(provenance, classMemberValueProvenance(owner, member, context));
        } else {
          enqueueExpressions(pending, [node.expression, node.argumentExpression]);
        }
      } else if (isObjectLiteralExpression(node)) {
        for (const property of node.properties) {
          if (isPropertyAssignment(property)) {
            pending.push(property.initializer);
          } else if (isShorthandPropertyAssignment(property)) {
            const binding = model.resolveIdentifier(property.name);
            if (binding) {
              addProvenance(provenance, bindingProvenance(binding, context, property.name));
            }
          } else if (isSpreadAssignment(property)) {
            pending.push(property.expression);
          } else if (isMethodDeclaration(property) || isGetAccessorDeclaration(property)) {
            addProvenance(provenance, callableOutputProvenance(property, context));
          }
        }
      } else if (isArrayLiteralExpression(node)) {
        for (const element of node.elements) {
          pending.push(isSpreadElement(element) ? element.expression : element);
        }
      } else if (isConditionalExpression(node)) {
        enqueueExpressions(pending, [node.whenTrue, node.whenFalse]);
      } else if (isCallExpression(node)) {
        const callables = callableDefinitions(node.expression, new Set());
        if (callables.length > 0) {
          for (const callable of callables) {
            addProvenance(provenance, callableOutputProvenance(callable, context, node.arguments));
          }
        } else if (
          !knownCallResultCannotContainArgument(node.expression) &&
          (isTransparentValueCall(node.expression) || unknownCallCanReturnArgument(node.expression))
        ) {
          enqueueExpressions(pending, node.arguments ?? []);
        }
      } else if (isNewExpression(node)) {
        const classes = classDefinitions(node.expression, new Set());
        if (classes.length > 0) {
          for (const classNode of classes) {
            addProvenance(
              provenance,
              classOutputProvenance(classNode, context, node.arguments ?? []),
            );
          }
        } else if (unknownCallCanReturnArgument(node.expression)) {
          enqueueExpressions(pending, node.arguments ?? []);
        }
      } else if (
        isBinaryExpression(node) &&
        binaryOperatorCanReturnOperand(node.operatorToken.kind)
      ) {
        enqueueExpressions(pending, [node.left, node.right]);
      } else if (isAwaitExpression(node) || isYieldExpression(node)) {
        if (node.expression) pending.push(node.expression);
      }
    }
    return provenance;
  }

  function callableDefinitions(node, seenBindings) {
    node = unwrapTransparentExpression(node);
    if (isFunctionNode(node)) return node.body ? [node] : [];
    if (isConditionalExpression(node)) {
      return [
        ...callableDefinitions(node.whenTrue, seenBindings),
        ...callableDefinitions(node.whenFalse, seenBindings),
      ];
    }
    if (!isIdentifier(node)) return [];
    const binding = model.resolveIdentifier(node);
    if (!binding || seenBindings.has(binding)) return [];
    seenBindings.add(binding);
    return effectiveDefinitions(binding, node).flatMap((definition) => {
      if (definition.kind === "function") return definition.node.body ? [definition.node] : [];
      if (definition.kind === "expression") {
        return callableDefinitions(definition.node, seenBindings);
      }
      return [];
    });
  }

  function classDefinitions(node, seenBindings) {
    node = unwrapTransparentExpression(node);
    if (isClassDeclaration(node) || isClassExpression(node)) return [node];
    if (isConditionalExpression(node)) {
      return [
        ...classDefinitions(node.whenTrue, seenBindings),
        ...classDefinitions(node.whenFalse, seenBindings),
      ];
    }
    if (!isIdentifier(node)) return [];
    const binding = model.resolveIdentifier(node);
    if (!binding || seenBindings.has(binding)) return [];
    seenBindings.add(binding);
    return effectiveDefinitions(binding, node).flatMap((definition) => {
      if (definition.kind === "class") return [definition.node];
      if (definition.kind === "expression") return classDefinitions(definition.node, seenBindings);
      return [];
    });
  }

  function callableOutputProvenance(node, parentContext, argumentsList = []) {
    if (parentContext.activeCallables.has(node)) return new Set();
    parentContext.activeCallables.add(node);
    const context = createCallableContext(node, parentContext, argumentsList);
    try {
      if (isArrowFunction(node) && node.body && !isBlock(node.body)) {
        return expressionProvenance(node.body, context);
      }
      const provenance = new Set();
      if (node.body) collectCallableOutputs(node.body, context, provenance);
      return provenance;
    } finally {
      parentContext.activeCallables.delete(node);
    }
  }

  function createCallableContext(node, parentContext, argumentsList = []) {
    const context = createContext(parentContext);
    for (const [index, parameter] of (node.parameters ?? []).entries()) {
      const argument = parameter.dotDotDotToken
        ? undefined
        : argumentsList[index]
          ? isSpreadElement(argumentsList[index])
            ? argumentsList[index].expression
            : argumentsList[index]
          : parameter.initializer;
      for (const { binding, path } of model.bindingEntriesForName(parameter.name)) {
        const parameterFact = parameter.dotDotDotToken
          ? valueFact(
              provenanceForExpressions(argumentsList.slice(index), parentContext),
              "nonundefined",
            )
          : projectedExpressionFact(argument, path, context);
        context.overrides.set(binding, parameterFact);
        if (path.length === 0 && argument) {
          context.sourceOverrides.set(binding, {
            context: argument === parameter.initializer ? context : parentContext,
            expressions: [argument],
          });
        }
      }
    }
    return context;
  }

  function provenanceForExpressions(expressions, context) {
    const provenance = new Set();
    for (const expression of expressions) {
      addProvenance(
        provenance,
        expressionProvenance(
          isSpreadElement(expression) ? expression.expression : expression,
          context,
        ),
      );
    }
    return provenance;
  }

  function collectCallableOutputs(node, context, provenance) {
    const pending = [node];
    while (pending.length > 0) {
      const current = pending.pop();
      if (isReturnStatement(current) || isYieldExpression(current)) {
        if (current.expression) {
          addProvenance(provenance, expressionProvenance(current.expression, context));
        }
        continue;
      }
      if (
        current !== node &&
        (isFunctionNode(current) || isClassDeclaration(current) || isClassExpression(current))
      ) {
        continue;
      }
      current.forEachChild((child) => {
        pending.push(child);
      });
    }
  }

  function effectiveClassAssignments(node, memberName) {
    const groups = new Map();
    for (const assignment of model.assignmentsForClass(node)) {
      if (memberName !== undefined && assignment.member !== memberName) continue;
      let callableGroups = groups.get(assignment.member);
      if (!callableGroups) {
        callableGroups = new Map();
        groups.set(assignment.member, callableGroups);
      }
      const key = assignment.ownerCallable ?? node;
      const records = callableGroups.get(key) ?? [];
      records.push(assignment);
      callableGroups.set(key, records);
    }
    const effective = [];
    for (const callableGroups of groups.values()) {
      for (const records of callableGroups.values()) {
        let values = [];
        for (const assignment of records.sort((left, right) => left.position - right.position)) {
          if (assignment.write === "replace") values = [assignment];
          else values.push(assignment);
        }
        effective.push(...values);
      }
    }
    return effective;
  }

  function classOutputProvenance(node, context, argumentsList = []) {
    if (context.activeClasses.has(node)) return new Set();
    context.activeClasses.add(node);
    const provenance = new Set();
    const hadInstanceContext = context.classInstanceContexts.has(node);
    const previousInstanceContext = context.classInstanceContexts.get(node);
    try {
      const constructor = node.members.find((member) => isConstructorDeclaration(member));
      const constructorContext = constructor
        ? createCallableContext(constructor, context, argumentsList)
        : context;
      context.classInstanceContexts.set(node, constructorContext);
      if (constructor) {
        for (const parameter of constructor.parameters ?? []) {
          if (!isPublicParameterProperty(parameter)) continue;
          for (const { binding } of model.bindingEntriesForName(parameter.name)) {
            addProvenance(provenance, bindingProvenance(binding, constructorContext));
          }
        }
      }
      for (const member of node.members) {
        if (isPrivateClassMember(member)) continue;
        if (isPropertyDeclaration(member) && member.initializer) {
          addProvenance(provenance, expressionProvenance(member.initializer, context));
        } else if (isGetAccessorDeclaration(member) || isMethodDeclaration(member)) {
          addProvenance(provenance, callableOutputProvenance(member, context));
        }
      }
      for (const assignment of effectiveClassAssignments(node)) {
        if (assignment.private || classMemberIsPrivate(node, assignment.member)) continue;
        const assignmentContext = assignment.ownerCallable
          ? assignment.ownerCallable === constructor
            ? constructorContext
            : createCallableContext(assignment.ownerCallable, context)
          : context;
        addProvenance(provenance, expressionProvenance(assignment.node, assignmentContext));
      }
      return provenance;
    } finally {
      if (hadInstanceContext) context.classInstanceContexts.set(node, previousInstanceContext);
      else context.classInstanceContexts.delete(node);
      context.activeClasses.delete(node);
    }
  }

  function classMemberValueProvenance(node, memberName, context) {
    let activeMembers = context.activeMemberClasses.get(node);
    if (!activeMembers) {
      activeMembers = new Set();
      context.activeMemberClasses.set(node, activeMembers);
    }
    if (activeMembers.has(memberName)) return new Set();
    activeMembers.add(memberName);
    const provenance = new Set();
    try {
      for (const member of node.members) {
        if (isConstructorDeclaration(member)) {
          const instanceContext = context.classInstanceContexts.get(node) ?? context;
          for (const parameter of member.parameters ?? []) {
            if (classMemberName(parameter.name) !== memberName) continue;
            for (const { binding } of model.bindingEntriesForName(parameter.name)) {
              addProvenance(provenance, bindingProvenance(binding, instanceContext));
            }
          }
          continue;
        }
        if (classMemberName(member.name) !== memberName) continue;
        if (isPropertyDeclaration(member) && member.initializer) {
          addProvenance(provenance, expressionProvenance(member.initializer, context));
        }
      }
      for (const assignment of effectiveClassAssignments(node, memberName)) {
        addProvenance(provenance, expressionProvenance(assignment.node, context));
      }
      return provenance;
    } finally {
      activeMembers.delete(memberName);
    }
  }

  function unknownCallCanReturnArgument(node) {
    node = unwrapTransparentExpression(node);
    if (isIdentifier(node)) return true;
    if (!isPropertyAccessExpression(node) && !isElementAccessExpression(node)) return false;
    const receiver = unwrapTransparentExpression(node.expression);
    if (!isIdentifier(receiver)) return false;
    const binding = model.resolveIdentifier(receiver);
    return Boolean(binding?.importSpecifiers.size);
  }

  function knownCallResultCannotContainArgument(node) {
    node = unwrapTransparentExpression(node);
    if (isKnownPrimitiveSanitizer(node) && !model.resolveIdentifier(node)) return true;
    if (!isIdentifier(node)) return false;
    const binding = model.resolveIdentifier(node);
    return [...(binding?.importSpecifiers ?? [])].some(
      (specifier) =>
        specifier === "drizzle-orm" ||
        specifier.startsWith("drizzle-orm/") ||
        (node.text === "decodeJson" && /(?:^|\/)shared\/json-codec$/.test(specifier)),
    );
  }

  const rootContext = createContext();
  return {
    forBinding: (binding) => bindingProvenance(binding, rootContext),
    forDefinition: (definition) => definitionProvenance(definition, rootContext),
    forExpression: (expression) => expressionProvenance(expression, rootContext),
  };
}

function enqueueExpressions(target, expressions) {
  for (const expression of expressions) {
    if (expression) target.push(expression);
  }
}

function isPrivateClassMember(member) {
  return (
    (member.name && isPrivateIdentifier(member.name)) ||
    (member.modifiers?.some((modifier) => modifier.kind === SyntaxKind.PrivateKeyword) ?? false)
  );
}

function classMemberIsPrivate(node, memberName) {
  return node.members.some(
    (member) => classMemberName(member.name) === memberName && isPrivateClassMember(member),
  );
}

function isPublicParameterProperty(parameter) {
  const modifiers = new Set(parameter.modifiers?.map((modifier) => modifier.kind) ?? []);
  const isParameterProperty = [
    SyntaxKind.PublicKeyword,
    SyntaxKind.PrivateKeyword,
    SyntaxKind.ProtectedKeyword,
    SyntaxKind.ReadonlyKeyword,
  ].some((kind) => modifiers.has(kind));
  return (
    isParameterProperty &&
    !modifiers.has(SyntaxKind.PrivateKeyword) &&
    !modifiers.has(SyntaxKind.ProtectedKeyword)
  );
}

function isKnownPrimitiveSanitizer(node) {
  node = unwrapTransparentExpression(node);
  return (
    isIdentifier(node) && ["BigInt", "Boolean", "Number", "String", "Symbol"].includes(node.text)
  );
}

function isTransparentValueCall(node) {
  node = unwrapTransparentExpression(node);
  if (isIdentifier(node)) return node.text === "structuredClone";
  if (!isPropertyAccessExpression(node) || !isIdentifier(node.expression)) return false;
  const transparentMethods = new Map([
    ["Array", new Set(["from"])],
    ["Object", new Set(["assign", "freeze", "preventExtensions", "seal"])],
    ["Promise", new Set(["resolve"])],
  ]);
  return transparentMethods.get(node.expression.text)?.has(node.name.text) ?? false;
}

function binaryOperatorCanReturnOperand(kind) {
  return [
    SyntaxKind.AmpersandAmpersandToken,
    SyntaxKind.BarBarToken,
    SyntaxKind.QuestionQuestionToken,
    SyntaxKind.CommaToken,
    SyntaxKind.EqualsToken,
  ].includes(kind);
}

function addProvenance(target, source) {
  for (const specifier of source) target.add(specifier);
}

function actualLineCount(source) {
  if (source.length === 0) return 0;
  const newlineCount = source.match(/\n/g)?.length ?? 0;
  return newlineCount + (source.endsWith("\n") ? 0 : 1);
}

function hasOrmAssignmentTarget(node) {
  node = unwrapTransparentExpression(node);
  if (!isObjectLiteralExpression(node)) return false;

  return node.properties.some((property) => {
    if (isShorthandPropertyAssignment(property)) return property.name.text === "orm";
    if (!isPropertyAssignment(property)) return false;
    return (
      staticPropertyName(property.name) === "orm" || hasOrmAssignmentTarget(property.initializer)
    );
  });
}

function staticString(node) {
  if (!node) return undefined;
  node = unwrapTransparentExpression(node);
  if (isStringLiteral(node) || isNoSubstitutionTemplateLiteral(node)) return node.text;
  return undefined;
}

function unwrapTransparentExpression(node) {
  while (
    isParenthesizedExpression(node) ||
    isAsExpression(node) ||
    isTypeAssertion(node) ||
    isSatisfiesExpression(node) ||
    isNonNullExpression(node)
  ) {
    node = node.expression;
  }
  return node;
}

function staticPropertyName(node) {
  if (!node) return undefined;
  if (isIdentifier(node)) return node.text;
  if (isComputedPropertyName(node)) return staticString(node.expression);
  return staticString(node);
}

function resolveModuleSpecifier(importer, specifier) {
  if (specifier.startsWith(".")) return resolveImport(importer, specifier);
  if (specifier.startsWith("@/") && relative(root, importer).startsWith("apps/client/src/")) {
    return resolveImport(
      resolve(root, "apps/client/src/__alias_importer__.ts"),
      `./${specifier.slice(2)}`,
    );
  }
  const packageTarget = packageSpecifiers.get(specifier);
  return packageTarget && sourceSet.has(packageTarget) ? packageTarget : undefined;
}

function resolveDatabaseEntrypoints(importer, edge) {
  const directSpecifier = databaseSpecifiers.get(edge.specifier);
  if (directSpecifier) return new Set([directSpecifier]);

  const target = resolveModuleSpecifier(importer, edge.specifier);
  return target ? collectDatabaseEntrypoints(target) : new Set();
}

function collectDatabaseEntrypoints(file) {
  const entrypoints = new Set();
  const visited = new Set();

  function collect(current) {
    if (visited.has(current)) return;
    visited.add(current);

    const directEntrypoint = databaseEntrypoints.get(current);
    if (directEntrypoint) {
      entrypoints.add(directEntrypoint);
      return;
    }
    for (const edge of sourceFacts.get(current)?.edges ?? []) {
      if (edge.kind !== "export" || edge.viaCallableOutput) continue;
      const directSpecifier = databaseSpecifiers.get(edge.specifier);
      if (directSpecifier) {
        entrypoints.add(directSpecifier);
        continue;
      }
      const target = resolveModuleSpecifier(current, edge.specifier);
      if (target) collect(target);
    }
  }

  collect(file);
  return entrypoints;
}

function collectReexportTargets(file) {
  const targets = new Set();
  const visited = new Set([file]);

  function collect(current) {
    for (const edge of sourceFacts.get(current)?.edges ?? []) {
      if (edge.kind !== "export") continue;
      const target = resolveModuleSpecifier(current, edge.specifier);
      if (!target) continue;
      targets.add(target);
      if (visited.has(target)) continue;
      visited.add(target);
      collect(target);
    }
  }

  collect(file);
  return targets;
}

function resolveImport(importer, specifier) {
  const base = resolve(dirname(importer), specifier);
  const explicitTypeScriptFile = /\.tsx?$/.test(base) ? [base] : [];
  const emittedJavaScriptSource = /\.[cm]?js$/.test(base)
    ? [base.replace(/\.[cm]?js$/, ".ts"), base.replace(/\.[cm]?js$/, ".tsx")]
    : [];
  for (const candidate of new Set([
    ...explicitTypeScriptFile,
    `${base}.ts`,
    `${base}.tsx`,
    ...emittedJavaScriptSource,
    resolve(base, "index.ts"),
    resolve(base, "index.tsx"),
  ])) {
    if (sourceSet.has(candidate)) return candidate;
  }
  return undefined;
}

function isTestFile(workspacePath) {
  return /(?:^|\/)test(?:\/|$)|\.(?:test|spec)\.tsx?$/.test(workspacePath);
}

function isDatabaseOwnerSchema(file) {
  return /^packages\/database\/src\/.+\/schema\.tsx?$/.test(relative(root, file));
}

function enforceServerFolderDirection(importer, target, output) {
  const match = /^apps\/server\/src\/(platform|rendering|assets|web)\//.exec(importer);
  if (!match) return;
  const owner = match[1];
  if (owner === "platform" && target.startsWith("apps/server/src/channels/")) {
    output.push(`${importer}: platform must not import channels`);
  }
  if (
    (owner === "rendering" || owner === "assets" || owner === "web") &&
    target.startsWith("apps/server/src/public/")
  ) {
    output.push(`${importer}: ${owner} must not import public`);
  }
}

function visit(file) {
  if (visited.has(file)) return;
  if (visiting.has(file)) {
    const start = stack.indexOf(file);
    const cycle = [...stack.slice(start), file].map((item) => relative(root, item)).join(" -> ");
    violations.push(`dependency cycle: ${cycle}`);
    return;
  }
  visiting.add(file);
  stack.push(file);
  for (const dependency of graph.get(file)) visit(dependency);
  stack.pop();
  visiting.delete(file);
  visited.add(file);
}
