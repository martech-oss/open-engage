async function collectSourceFiles(directory, output) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (["dist", "node_modules", ".wrangler"].includes(entry.name)) continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await collectSourceFiles(path, output);
    else if (
      /\.(?:ts|tsx)$/.test(entry.name) &&
      !generatedSourcePaths.has(relative(root, path)) &&
      !generatedDeclarationPaths.has(relative(root, path))
    )
      output.push(path);
  }
}

function extractSourceFacts(sourceFiles) {
  if (sourceFiles.length === 0) return new Map();

  const api = new TypeScriptApi({ cwd: root });
  let snapshot;
  try {
    snapshot = api.updateSnapshot({ openFiles: sourceFiles });
    return new Map(
      sourceFiles.map((file) => {
        const project = snapshot.getDefaultProjectForFile(file);
        const sourceFile = project?.program.getSourceFile(file);
        if (!sourceFile) throw new Error(`TypeScript could not parse ${relative(root, file)}`);
        if (project.program.getSyntacticDiagnostics(file).length > 0) {
          throw new Error(`TypeScript could not parse ${relative(root, file)}`);
        }
        return [file, extractAstFacts(sourceFile)];
      }),
    );
  } finally {
    snapshot?.dispose();
    api.close();
  }
}

function extractAstFacts(sourceFile) {
  const edges = [];
  const lexicalModel = createLexicalModel(sourceFile);
  const runtimeImports = collectRuntimeImportBindings(sourceFile, lexicalModel);
  const functionLikeSpans = [];
  let hasClientRolePermissionLogic = false;
  let hasRpcTransportSetup = false;
  let hasRouteSsrDisabled = false;
  let hasStaticOrmAccess = false;

  function addEdge(kind, node, metadata = {}) {
    const specifier = staticString(node);
    if (specifier !== undefined) edges.push({ kind, specifier, ...metadata });
  }

  function visit(node) {
    if (
      isFunctionDeclaration(node) ||
      isArrowFunction(node) ||
      isFunctionExpression(node) ||
      isMethodDeclaration(node) ||
      isConstructorDeclaration(node) ||
      isGetAccessorDeclaration(node) ||
      isSetAccessorDeclaration(node) ||
      isClassStaticBlockDeclaration(node)
    ) {
      const start = sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile)).line;
      const end = sourceFile.getLineAndCharacterOfPosition(
        Math.max(node.getStart(sourceFile), node.end - 1),
      ).line;
      functionLikeSpans.push({ lineCount: end - start + 1, startLine: start + 1 });
    }
    if (isImportDeclaration(node)) {
      addEdge("import", node.moduleSpecifier, { runtime: importDeclarationIsRuntime(node) });
    } else if (isExportDeclaration(node)) {
      if (node.moduleSpecifier) {
        addEdge("export", node.moduleSpecifier, {
          exportsAll: !node.exportClause,
          runtime: exportDeclarationIsRuntime(node),
        });
      }
    } else if (isImportTypeNode(node)) {
      addEdge(
        "import-type",
        isLiteralTypeNode(node.argument) ? node.argument.literal : node.argument,
      );
    } else if (isCallExpression(node) && node.expression.kind === SyntaxKind.ImportKeyword) {
      // Computed dynamic imports cannot form a canonical static dependency edge and are
      // intentionally ignored. String literals and no-substitution templates are retained.
      addEdge("dynamic-import", node.arguments[0], { runtime: true });
    }

    if (
      (isPropertyAccessExpression(node) && isIdentifier(node.name) && node.name.text === "orm") ||
      (isElementAccessExpression(node) && staticString(node.argumentExpression) === "orm") ||
      (isBindingElement(node) &&
        isObjectBindingPattern(node.parent) &&
        staticPropertyName(node.propertyName ?? node.name) === "orm") ||
      (isBinaryExpression(node) &&
        node.operatorToken.kind === SyntaxKind.EqualsToken &&
        hasOrmAssignmentTarget(node.left))
    ) {
      hasStaticOrmAccess = true;
    }
    if (isObjectLiteralExpression(node) && objectContainsDisabledSsr(node, lexicalModel)) {
      hasRouteSsrDisabled = true;
    }
    if (isDirectRolePermissionExpression(node, lexicalModel)) {
      hasClientRolePermissionLogic = true;
    }
    if (
      (isCallExpression(node) || isNewExpression(node)) &&
      isRpcTransportSetup(node, lexicalModel, runtimeImports)
    ) {
      hasRpcTransportSetup = true;
    }

    node.forEachChild(visit);
  }

  sourceFile.forEachChild(visit);
  const provenance = createProvenanceAnalyzer(lexicalModel);
  const exportedProvenanceEdges = [];
  function addExportedProvenance(specifiers, viaCallableOutput) {
    for (const specifier of specifiers) {
      exportedProvenanceEdges.push({ specifier, viaCallableOutput });
    }
  }
  for (const binding of lexicalModel.exportedBindings) {
    addExportedProvenance(provenance.forBinding(binding), bindingIsCallableSurface(binding));
  }
  for (const expression of lexicalModel.exportedExpressions) {
    addExportedProvenance(
      provenance.forExpression(expression),
      expressionIsCallableSurface(expression),
    );
  }
  for (const definition of lexicalModel.exportedDefinitions) {
    addExportedProvenance(
      provenance.forDefinition(definition),
      definitionIsCallableSurface(definition),
    );
  }
  for (const { specifier, viaCallableOutput } of exportedProvenanceEdges) {
    edges.push({
      exportsAll: false,
      kind: "export",
      specifier,
      viaCallableOutput,
      viaImportedBinding: true,
    });
  }
  return {
    edges,
    functionLikeSpans,
    hasClientRolePermissionLogic,
    hasRpcTransportSetup,
    hasRouteSsrDisabled,
    hasStaticOrmAccess,
    source: sourceFile.text,
  };
}

function importDeclarationIsRuntime(node) {
  const clause = node.importClause;
  if (!clause) return true;
  if (clause.isTypeOnly) return false;
  if (clause.name) return true;
  const bindings = clause.namedBindings;
  if (!bindings || isNamespaceImport(bindings)) return Boolean(bindings);
  return (
    isNamedImports(bindings) &&
    (bindings.elements.length === 0 || bindings.elements.some((element) => !element.isTypeOnly))
  );
}

function exportDeclarationIsRuntime(node) {
  if (node.isTypeOnly) return false;
  const exports = node.exportClause;
  if (!exports || !isNamedExports(exports)) return true;
  return exports.elements.length === 0 || exports.elements.some((element) => !element.isTypeOnly);
}

function collectRuntimeImportBindings(sourceFile, lexicalModel) {
  const importsByBinding = new Map();
  function record(identifier, metadata) {
    const binding = lexicalModel.resolveIdentifier(identifier);
    if (!binding) return;
    const imports = importsByBinding.get(binding) ?? [];
    imports.push(metadata);
    importsByBinding.set(binding, imports);
  }
  for (const statement of sourceFile.statements) {
    if (!isImportDeclaration(statement) || !statement.importClause) continue;
    const specifier = staticString(statement.moduleSpecifier);
    if (specifier === undefined) continue;
    const clause = statement.importClause;
    if (clause.name && !clause.isTypeOnly) {
      record(clause.name, { importedName: "default", namespace: false, specifier });
    }
    const bindings = clause.namedBindings;
    if (bindings && isNamespaceImport(bindings) && !clause.isTypeOnly) {
      record(bindings.name, { importedName: "*", namespace: true, specifier });
    } else if (bindings && isNamedImports(bindings)) {
      for (const element of bindings.elements) {
        if (clause.isTypeOnly || element.isTypeOnly) continue;
        record(element.name, {
          importedName: (element.propertyName ?? element.name).text,
          namespace: false,
          specifier,
        });
      }
    }
  }
  return importsByBinding;
}

function isRpcTransportSetup(node, lexicalModel, runtimeImports) {
  const callee = unwrapTransparentExpression(node.expression);
  let records = [];
  let importedName;
  if (isIdentifier(callee)) {
    const binding = lexicalModel.resolveIdentifier(callee);
    records = binding ? (runtimeImports.get(binding) ?? []) : [];
    importedName = records[0]?.importedName;
  } else if (isPropertyAccessExpression(callee) && isIdentifier(callee.expression)) {
    const binding = lexicalModel.resolveIdentifier(callee.expression);
    records = binding
      ? (runtimeImports.get(binding) ?? []).filter((record) => record.namespace)
      : [];
    importedName = callee.name.text;
  }
  return records.some(({ specifier }) => {
    if (isNewExpression(node)) {
      return specifier === "@orpc/client/fetch" && importedName === "RPCLink";
    }
    return (
      (specifier === "@orpc/client" && importedName === "createORPCClient") ||
      (specifier === "@orpc/tanstack-query" && importedName === "createTanstackQueryUtils")
    );
  });
}

function objectContainsDisabledSsr(node, lexicalModel, seenBindings = new Set()) {
  const target = unwrapTransparentExpression(node);
  if (isIdentifier(target)) {
    const binding = lexicalModel.resolveIdentifier(target);
    if (!binding || seenBindings.has(binding)) return false;
    const nestedSeen = new Set(seenBindings);
    nestedSeen.add(binding);
    return binding.definitions.some(
      (definition) =>
        definition.kind === "expression" &&
        objectContainsDisabledSsr(definition.node, lexicalModel, nestedSeen),
    );
  }
  if (!isObjectLiteralExpression(target)) return false;
  return target.properties.some((property) => {
    if (isPropertyAssignment(property) && staticPropertyName(property.name) === "ssr") {
      return expressionResolvesFalse(property.initializer, lexicalModel);
    }
    if (isShorthandPropertyAssignment(property) && property.name.text === "ssr") {
      return expressionResolvesFalse(property.name, lexicalModel);
    }
    return (
      isSpreadAssignment(property) &&
      objectContainsDisabledSsr(property.expression, lexicalModel, seenBindings)
    );
  });
}

function expressionResolvesFalse(node, lexicalModel, seenBindings = new Set()) {
  const target = unwrapTransparentExpression(node);
  if (target.kind === SyntaxKind.FalseKeyword) return true;
  if (!isIdentifier(target)) return false;
  const binding = lexicalModel.resolveIdentifier(target);
  if (!binding || seenBindings.has(binding)) return false;
  const nestedSeen = new Set(seenBindings);
  nestedSeen.add(binding);
  return binding.definitions.some(
    (definition) =>
      definition.kind === "expression" &&
      expressionResolvesFalse(definition.node, lexicalModel, nestedSeen),
  );
}

function isDirectRolePermissionExpression(node, lexicalModel) {
  if (isNewExpression(node) && isRolePermissionCollection(node, lexicalModel)) return true;
  if (
    isBinaryExpression(node) &&
    [
      SyntaxKind.EqualsEqualsToken,
      SyntaxKind.EqualsEqualsEqualsToken,
      SyntaxKind.ExclamationEqualsToken,
      SyntaxKind.ExclamationEqualsEqualsToken,
    ].includes(node.operatorToken.kind)
  ) {
    return (
      (isRoleReference(node.left, lexicalModel) && isWorkspaceRoleLiteral(node.right)) ||
      (isRoleReference(node.right, lexicalModel) && isWorkspaceRoleLiteral(node.left))
    );
  }
  if (
    isCallExpression(node) &&
    isPropertyAccessExpression(unwrapTransparentExpression(node.expression))
  ) {
    const callee = unwrapTransparentExpression(node.expression);
    if (
      (callee.name.text === "includes" || callee.name.text === "has") &&
      node.arguments.some((argument) => isRoleReference(argument, lexicalModel)) &&
      isRolePermissionCollection(callee.expression, lexicalModel)
    ) {
      return true;
    }
  }
  return false;
}

function isRoleReference(node, lexicalModel, seenBindings = new Set()) {
  const target = unwrapTransparentExpression(node);
  if (
    (isIdentifier(target) && /role$/i.test(target.text)) ||
    (isPropertyAccessExpression(target) && target.name.text === "role") ||
    (isElementAccessExpression(target) && staticString(target.argumentExpression) === "role")
  ) {
    return true;
  }
  if (!isIdentifier(target)) return false;
  const binding = lexicalModel.resolveIdentifier(target);
  if (!binding || seenBindings.has(binding)) return false;
  const nestedSeen = new Set(seenBindings);
  nestedSeen.add(binding);
  return binding.definitions.some((definition) => {
    if (
      definition.kind === "projection" &&
      definition.path.some((step) => step.kind === "object" && step.key === "role")
    ) {
      return true;
    }
    return (
      definition.kind === "expression" && isRoleReference(definition.node, lexicalModel, nestedSeen)
    );
  });
}

function isWorkspaceRoleLiteral(node) {
  // Keep this permission ratchet synchronized with WORKSPACE_ROLES in
  // packages/core/src/shared/schema.ts.
  return ["owner", "admin", "marketer", "analyst", "viewer"].includes(staticString(node));
}

function isRolePermissionCollection(node, lexicalModel, seenBindings = new Set()) {
  const target = unwrapTransparentExpression(node);
  if (isArrayLiteralExpression(target)) {
    return target.elements.some(isWorkspaceRoleLiteral);
  }
  if (
    isNewExpression(target) &&
    isIdentifier(target.expression) &&
    target.expression.text === "Set"
  ) {
    return (
      target.arguments?.some((argument) =>
        isRolePermissionCollection(argument, lexicalModel, seenBindings),
      ) ?? false
    );
  }
  if (!isIdentifier(target)) return false;
  if (/(?:role|permission)/i.test(target.text)) return true;
  const binding = lexicalModel.resolveIdentifier(target);
  if (!binding || seenBindings.has(binding)) return false;
  const nestedSeen = new Set(seenBindings);
  nestedSeen.add(binding);
  return binding.definitions.some(
    (definition) =>
      definition.kind === "expression" &&
      isRolePermissionCollection(definition.node, lexicalModel, nestedSeen),
  );
}

